"""Builds infra/prometheus/rules/shop.yml from eval/telemetry/signals.py.

The alerts that open incidents use exactly the PromQL the eval runner measures
(signals.promql), so a live alert and the runner's synthetic alert watch the
same number. Alert names are the ones the cases use (alert.name); the signal
for each name comes from eval/runner/alerts.py (signal_for).

    python infra/prometheus/build_rules.py          # rewrite shop.yml
    python infra/prometheus/build_rules.py --check  # exit 1 if shop.yml is stale (CI)

Thresholds. The runner fires on a move from the baseline it measured just
before injecting (MOVE_THRESHOLDS). A live rule has no injection time, so:
  - error_rate and error_count use the absolute part of that rule (the shop
    sits near zero errors at rest);
  - latency, memory, traffic and lag compare with the same signal 15-45
    minutes earlier, using the probe's absolute and relative margins. These
    stay silent until the stack has run for about 45 minutes.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from eval.probes.faults import MOVE_THRESHOLDS  # noqa: E402
from eval.runner.alerts import signal_for  # noqa: E402
from eval.telemetry.signals import promql  # noqa: E402

OUT = Path(__file__).resolve().parent / "rules" / "shop.yml"
WINDOW = "5m"

# alert name -> (service, for, summary). Names and services match the cases'
# alert specs; add a line here when a case names a new alert.
ALERTS = {
    "CheckoutErrorRateHigh": ("checkout", "5m", "Checkout error rate above 5% for 5 minutes"),
    "CartErrorRateHigh": ("cart", "2m", "Cart is returning errors"),
    "ProductCatalogErrorRateHigh": ("product-catalog", "2m", "Product catalog error rate above 5%"),
    "AdErrorRateHigh": ("ad", "2m", "Ad service error rate above 5%"),
    "ProductCatalogLatencyHigh": ("product-catalog", "2m", "Product catalog p95 latency well above normal"),
    "FrontendLatencyHigh": ("frontend-proxy", "2m", "Frontend p95 latency well above normal"),
    "FrontendTrafficHigh": ("frontend", "2m", "Frontend traffic at least double normal"),
    "EmailMemoryHigh": ("email", "5m", "Email service memory growing"),
    "KafkaConsumerLagHigh": ("fraud-detection", "2m", "Order consumer lag growing (full shop only)"),
}


def baseline(query: str) -> str:
    return f"avg_over_time(({query})[30m:1m] offset 15m)"


def expr_for(signal: str, service: str) -> str:
    q = promql(signal, service, WINDOW)
    absolute, relative = MOVE_THRESHOLDS[signal]
    if signal == "error_rate":
        return f"({q}) > {absolute}"
    if signal == "error_count":
        return f"({q}) >= {absolute}"
    # Moved by at least the absolute margin and the relative margin over the earlier level.
    b = baseline(q)
    return f"({q}) > ({b}) + {absolute} and ({q}) > ({b}) * {1 + relative}"


def build() -> dict:
    rules = []
    for name, (service, wait, summary) in ALERTS.items():
        signal = signal_for(name)
        rules.append({
            "alert": name,
            "expr": expr_for(signal, service),
            "for": wait,
            "labels": {"severity": "page", "service": service, "signal": signal},
            "annotations": {"summary": summary, "value": "{{ $value }}"},
        })
    return {"groups": [{"name": "shop", "rules": rules}]}


def render() -> str:
    header = "# GENERATED by infra/prometheus/build_rules.py from eval/telemetry/signals.py. Do not edit.\n"
    return header + yaml.safe_dump(build(), sort_keys=False, width=200)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("infra/prometheus/rules/shop.yml is stale: run python infra/prometheus/build_rules.py")
            sys.exit(1)
        print("shop.yml is current")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)} ({len(ALERTS)} alerts)")
